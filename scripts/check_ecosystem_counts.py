"""Validate the ecosystem package counts that the docs advertise.

A recipe "uses" a toolkit package when its ``pyproject.toml`` declares it as a
dependency (``project.dependencies`` or any ``project.optional-dependencies``
group). Runtime imports are intentionally not scanned: an example generated by a
CLI declares the packages its template pulls in without importing them itself,
and the docs call that case out as *CLI-generated*.

The recipe list comes from the same loader as ``scripts/gen_recipe_table.py``.
Run ``python scripts/check_ecosystem_counts.py`` to validate the counts in the
README files and ``docs/toolkit-usage.md``; add ``--print`` to show the real
counts. ``azure-functions-scaffold`` is not counted: it is a CLI that generates
projects and no recipe declares it. ``make check`` runs it as part of ``generated-check``.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys
import tomllib

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from azure_functions_python_cookbook.recipes import RECIPES  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[1]
READMES = ("README.md", "README.ko.md", "README.ja.md", "README.zh-CN.md")
USAGE_DOC = REPO_ROOT / "docs" / "toolkit-usage.md"
PACKAGES = (
    "azure-functions-openapi",
    "azure-functions-validation",
    "azure-functions-logging",
    "azure-functions-db",
    "azure-functions-langgraph",
    "azure-functions-doctor",
)
_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def _declared(pyproject: Path) -> set[str]:
    project = tomllib.loads(pyproject.read_text(encoding="utf-8")).get("project", {})
    specs = list(project.get("dependencies", []))
    for group in project.get("optional-dependencies", {}).values():
        specs.extend(group)
    names = set()
    for spec in specs:
        match = _NAME.match(spec)
        if match:
            names.add(re.sub(r"[-_.]+", "-", match.group(1)).lower())
    return names


def count_declaring() -> dict[str, int]:
    counts = dict.fromkeys(PACKAGES, 0)
    for recipe in RECIPES:
        pyproject = recipe.directory / "pyproject.toml"
        if not pyproject.is_file():
            continue
        names = _declared(pyproject)
        for package in PACKAGES:
            if package in names:
                counts[package] += 1
    return counts


def _readme_rows(text: str) -> dict[str, int | None]:
    rows: dict[str, int | None] = {}
    for line in text.splitlines():
        match = re.match(r"^\| \[(azure-functions-[a-z]+)-python\]", line)
        if match:
            number = re.search(r"\d+", line.strip().strip("|").split("|")[-1])
            rows[match.group(1)] = int(number.group()) if number else None
    return rows


def _usage_rows(text: str) -> dict[str, int | None]:
    rows: dict[str, int | None] = {}
    for line in text.splitlines():
        match = re.match(r"^\| `(azure-functions-[a-z]+)` \| (\d+) \|", line)
        if match:
            rows[match.group(1)] = int(match.group(2))
    return rows


def find_drift(counts: dict[str, int]) -> list[str]:
    problems: list[str] = []
    sources = {
        name: _readme_rows((REPO_ROOT / name).read_text(encoding="utf-8")) for name in READMES
    }
    sources["docs/toolkit-usage.md"] = _usage_rows(USAGE_DOC.read_text(encoding="utf-8"))
    for source, rows in sources.items():
        for package, expected in counts.items():
            actual = rows.get(package)
            if actual != expected:
                problems.append(
                    f"{source}: {package} shows {actual} but recipes declare it in {expected}"
                )
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--print", action="store_true", help="Print the real counts and exit")
    args = parser.parse_args(argv)
    counts = count_declaring()
    if args.print:
        for package, count in counts.items():
            print(f"{package}: {count}")
        return 0
    problems = find_drift(counts)
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(
            "Ecosystem counts are stale. Real counts: "
            "python scripts/check_ecosystem_counts.py --print",
            file=sys.stderr,
        )
        return 1
    print("Ecosystem package counts match the recipes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
