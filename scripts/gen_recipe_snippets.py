"""Keep the highest-maintenance repeated recipe files in sync with one canonical copy.

Recipes stay standalone: every copy is a plain file inside its own recipe, nothing is imported
or shared at runtime, and there is no template language. The canonical copies live in
``scripts/recipe_snippets/``. Edit a canonical copy, run ``python scripts/gen_recipe_snippets.py``
to apply the update to every recipe that still carries the standard file, and review the diff.

A recipe whose copy intentionally differs is listed in ``VARIANTS`` with the reason, so every
divergence is deliberate and reviewable. ``--check`` (run by ``make check`` and CI) fails on a copy
that matches neither the canonical file nor a listed variant, and on a stale variant entry.
"""

from __future__ import annotations

import argparse
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = REPO_ROOT / "examples"
SNIPPETS = REPO_ROOT / "scripts" / "recipe_snippets"
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tools.recipe_discovery import recipe_files  # noqa: E402

_SCAFFOLD = "apis-and-ingress/scaffold_walkthrough_app"
_PERSONAL_AGENT = "ai-and-agents/personal_langgraph_agent"
_OPT_OUT = "apis-and-ingress/openapi_inference_opt_out"
_LEVEL_LOGGING = "stdlib logging with a level parameter and a recipe-specific docstring"


@dataclass(frozen=True)
class Snippet:
    """One repeated file: its path inside a recipe, canonical copy and deliberate variants."""

    relative: str
    canonical: str
    variants: Mapping[str, str] = field(default_factory=dict)


SNIPPET_FILES: tuple[Snippet, ...] = (
    Snippet(
        "Makefile",
        "recipe.Makefile",
        {
            _SCAFFOLD: "scaffold preset: configurable tooling flags and a doctor target",
            _PERSONAL_AGENT: "uv-based environment with a typecheck target",
        },
    ),
    Snippet(
        ".funcignore",
        "funcignore",
        {
            _SCAFFOLD: "generated by azure-functions-scaffold; kept verbatim",
            _OPT_OUT: "standard Functions exclusions (.git*, local.settings.json)",
            "security-and-tenancy/managed_identity_storage": "also excludes git metadata and *.pyc",
            "runtime-and-ops/concurrency_tuning": "also excludes git metadata and *.pyc",
            _PERSONAL_AGENT: "also excludes ruff and mypy caches",
        },
    ),
    Snippet(
        ".gitignore",
        "gitignore",
        {
            _SCAFFOLD: "generated by azure-functions-scaffold; kept verbatim",
            _OPT_OUT: "different ignore set (*.py[cod], no dist/ or build/)",
            _PERSONAL_AGENT: "also ignores .mypy_cache/ and keeps no dist/ or build/",
        },
    ),
    Snippet(
        "app/core/logging.py",
        "app_core_logging.py.txt",
        {
            _SCAFFOLD: "uses azure-functions-logging (JsonFormatter, get_logger)",
            "security-and-tenancy/managed_identity_storage": _LEVEL_LOGGING,
            "security-and-tenancy/managed_identity_servicebus": _LEVEL_LOGGING,
            "runtime-and-ops/concurrency_tuning": _LEVEL_LOGGING,
            "runtime-and-ops/host_json_tuning": _LEVEL_LOGGING,
            "guides/local_run_and_direct_invoke": _LEVEL_LOGGING,
        },
    ),
)


@dataclass(frozen=True)
class Problem:
    """A copy that needs attention: ``drift`` (fixable) or a bad ``variant`` entry."""

    kind: str
    recipe: str
    relative: str

    def __str__(self) -> str:
        return f"{self.kind}: {self.recipe}/{self.relative}"


def recipe_projects(examples: Path = EXAMPLES) -> tuple[Path, ...]:
    return tuple(path.parent for path in recipe_files(examples, "function_app.py"))


def find_problems(
    examples: Path,
    snippets: Sequence[Snippet] = SNIPPET_FILES,
    snippet_dir: Path = SNIPPETS,
) -> list[Problem]:
    """Every copy that is neither canonical nor a listed variant, plus bad variant entries."""
    projects = {p.relative_to(examples).as_posix(): p for p in recipe_projects(examples)}
    problems: list[Problem] = []
    for snippet in snippets:
        canonical = (snippet_dir / snippet.canonical).read_bytes()
        for recipe, reason in snippet.variants.items():
            if not reason.strip():
                problems.append(Problem("variant-without-reason", recipe, snippet.relative))
            copy = projects[recipe] / snippet.relative if recipe in projects else None
            if copy is None or not copy.is_file():
                problems.append(Problem("variant-for-missing-file", recipe, snippet.relative))
            elif copy.read_bytes() == canonical:
                problems.append(Problem("variant-equals-canonical", recipe, snippet.relative))
        for recipe, project in projects.items():
            copy = project / snippet.relative
            if copy.is_file() and recipe not in snippet.variants:
                if copy.read_bytes() != canonical:
                    problems.append(Problem("drift", recipe, snippet.relative))
    return problems


def sync(
    examples: Path,
    snippets: Sequence[Snippet] = SNIPPET_FILES,
    snippet_dir: Path = SNIPPETS,
) -> list[Path]:
    """Overwrite drifted standard copies with the canonical file; variants are never touched."""
    written: list[Path] = []
    for problem in find_problems(examples, snippets, snippet_dir):
        if problem.kind != "drift":
            continue
        snippet = next(s for s in snippets if s.relative == problem.relative)
        target = examples / problem.recipe / snippet.relative
        target.write_bytes((snippet_dir / snippet.canonical).read_bytes())
        written.append(target)
    return written


def main(
    argv: list[str] | None = None,
    examples: Path = EXAMPLES,
    snippets: Sequence[Snippet] = SNIPPET_FILES,
    snippet_dir: Path = SNIPPETS,
) -> int:
    parser = argparse.ArgumentParser(
        description="Apply or verify the canonical copies of repeated recipe files."
    )
    parser.add_argument("--check", action="store_true", help="Fail on drift; change nothing")
    args = parser.parse_args(argv)

    problems = find_problems(examples, snippets, snippet_dir)
    if not args.check:
        written = sync(examples, snippets, snippet_dir)
        for path in written:
            print(f"updated {path.relative_to(examples.parent)}")
        problems = [p for p in problems if p.kind != "drift"]
    if problems:
        print(
            "Recipe snippets need attention (see scripts/gen_recipe_snippets.py):", file=sys.stderr
        )
        for problem in problems:
            print(problem, file=sys.stderr)
        if args.check:
            print("Run: python scripts/gen_recipe_snippets.py", file=sys.stderr)
        return 1
    print("Recipe snippets are up to date." if args.check else "Recipe snippets synced.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
